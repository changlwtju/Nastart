#!/usr/bin/env python3
"""Structured private USB transport and read-only WDA scene/UI observations.

Importing opens no device. Callers must first pass the current per-device package
gate. This module neither creates sessions nor changes WDA settings/foreground.
UI transitions certify controls only, never pause, movie frames or frame pacing.
Use serially; save returned XML/PNG and any exception chains only in private evidence.
"""
import base64
from dataclasses import dataclass, field
import hashlib
import http.client
import json
import math
from pathlib import Path
import re
import runpy
import time
import xml.etree.ElementTree as ET

from wda_command_guard import GuardedWDA, ProtocolError, Reply, SceneChanged, decode_reply

FAST_SOURCE_ROUTE = '/source?excluded_attributes=visible,accessible,traits'


class OrientationChanged(SceneChanged):
    """The bound process stayed valid, but a read crossed device orientations."""


def tidevice_connector(uid):
    """Lazy factory; the installed system Python supplies tidevice."""
    def connect():
        runpy.run_path(str(Path(__file__).with_name('tidevice_private.py')))
        import tidevice
        return tidevice.Device(uid).create_inner_connection(8100)
    return connect


class USBTransport:
    def __init__(self, connect, *, timeout=15, save_reply=None):
        if not 0 < timeout <= 30:
            raise ValueError('USB timeout must be within 0..30 seconds')
        self.connect, self.timeout = connect, timeout
        if save_reply is not None and not callable(save_reply):
            raise TypeError('Private reply saver must be callable')
        self.save_reply = save_reply

    def request(self, path, data=None):
        # Paths are generated by the session adapter, never raw selectors/URLs.
        if not isinstance(path, str):
            raise ValueError('Invalid WDA request path')
        base, separator, query = path.partition('?')
        if (not re.fullmatch(r'/[A-Za-z0-9_./:-]+', base) or '..' in base or '//' in base
                or separator and (query != FAST_SOURCE_ROUTE.split('?', 1)[1]
                    or not re.fullmatch(r'/session/[A-Za-z0-9][A-Za-z0-9_-]*/source', base)
                    or data is not None)):
            raise ValueError('Invalid WDA request path')
        body = b'' if data is None else json.dumps(data, ensure_ascii=False).encode('utf-8')
        method = 'GET' if data is None else 'POST'
        header = (f'{method} {path} HTTP/1.1\r\nHost: localhost\r\n'
                  'Connection: close\r\nContent-Type: application/json\r\n'
                  f'Content-Length: {len(body)}\r\n\r\n').encode('ascii')
        connection = self.connect()
        try:
            sock = connection.get_socket()
            sock.settimeout(self.timeout)
            sock.sendall(header + body)
            response = http.client.HTTPResponse(sock)
            try:
                response.begin()
                # Keep status/body intact even for HTTP404; classification is above transport.
                reply = Reply(response.status, response.read())
                if self.save_reply is not None:
                    self.save_reply(reply)
                return reply
            finally:
                response.close()
        finally:
            connection.close()


@dataclass(frozen=True)
class Scene:
    session: str = field(repr=False)
    bundle: str
    pid: int
    orientation: str


@dataclass(frozen=True)
class UIObservation:
    scene: Scene
    started: float
    finished: float
    xml: str = field(repr=False)
    png: bytes = field(repr=False)

    def button_count(self, name, *, visible_only=True):
        tree = ET.fromstring(self.xml)
        return sum(e.tag == 'XCUIElementTypeButton' and e.get('name') == name
                   and (not visible_only or
                        e.get('visible') == 'true' and e.get('enabled') == 'true')
                   for e in tree.iter())


@dataclass(frozen=True)
class NativePiPObservation:
    scene: Scene
    started: float
    finished: float
    png: bytes = field(repr=False)
    container_rect: dict = field(repr=False)
    controls: tuple = field(repr=False)

    def button_count(self, name, *, visible_only=True):
        return sum(c['name'] == name and
                   (not visible_only or c['displayed'] and c['enabled']) for c in self.controls)

    def private_summary(self):
        return {'provenance': 'targeted WDA element reads; not a full UI source',
                'started': self.started, 'finished': self.finished,
                'containerRect': self.container_rect, 'controls': self.controls}


class USBSession:
    def __init__(self, transport, session, expected_bundle, expected_pid, *, clock=time.monotonic):
        if (not isinstance(session, str)
                or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]*', session)):
            raise ValueError('Invalid WDA session ID')
        if not isinstance(expected_bundle, str) or not expected_bundle:
            raise ValueError('Expected foreground bundle is required')
        if type(expected_pid) is not int or expected_pid <= 0:
            raise ValueError('Fresh expected foreground PID is required')
        self.transport, self.session = transport, session
        self.expected_bundle, self.expected_pid = expected_bundle, expected_pid
        self.clock = clock

    def send(self, route, body=None):
        # No session creation, app activation, settings mutation or arbitrary actions.
        read_routes = {'/wda/activeAppInfo', '/orientation', '/appium/settings',
                       '/source', '/screenshot', FAST_SOURCE_ROUTE}
        allowed = ((route in read_routes and body is None)
                   or (isinstance(route, str) and body is None
                       and re.fullmatch(r'/element/[A-Za-z0-9][A-Za-z0-9._:-]*/(displayed|enabled|rect)', route)
                       and '..' not in route)
                   or (route == '/elements' and isinstance(body, dict))
                   or (isinstance(route, str)
                       and re.fullmatch(r'/element/[A-Za-z0-9][A-Za-z0-9._:-]*/click', route)
                       and body == {} and '..' not in route))
        if not allowed:
            raise ValueError('Unsupported session command')
        result = self.transport.request('/session/' + self.session + route, body)
        # A returned session identity, when present, must match the bound session.
        # Error bodies still flow to decode_reply with their original status/body.
        try:
            envelope = json.loads(result.body)
        except (ValueError, UnicodeError):
            return result
        if isinstance(envelope, dict) and envelope.get('sessionId') not in (None, self.session):
            raise SceneChanged('Response belongs to another WDA session')
        return result

    def read(self, route):
        return decode_reply(self.send(route))

    def read_navigation_source(self):
        """Existing fast XML path; excluded visibility is UNKNOWN, never visible=False.

        For app navigation/geometry only. Native UI effect proofs still use full
        observe_ui() source, with explicit visible/enabled controls.
        """
        scene = self.live_scene()
        source = self.read(FAST_SOURCE_ROUTE)
        if not isinstance(source, str):
            raise ProtocolError('Navigation source must be XML text')
        try:
            ET.fromstring(source)
        except ET.ParseError as error:
            raise ProtocolError('Invalid navigation source XML') from error
        if self.live_scene() != scene:
            raise OrientationChanged('Orientation changed during navigation observation')
        return source

    def _foreground(self):
        value = self.read('/wda/activeAppInfo')
        if (not isinstance(value, dict) or value.get('bundleId') != self.expected_bundle
                or type(value.get('pid')) is not int or value['pid'] != self.expected_pid):
            raise SceneChanged('Expected foreground process is not current')
        return value['bundleId'], value['pid']

    def live_scene(self):
        # A pinned defaultActiveApplication can mask a real foreground change.
        settings = self.read('/appium/settings')
        if not isinstance(settings, dict) or settings.get('defaultActiveApplication') != 'auto':
            raise SceneChanged('Foreground observation requires automatic active application')
        before = self._foreground()
        orientation = self.read('/orientation')
        if orientation not in ('PORTRAIT', 'LANDSCAPE'):
            raise ProtocolError('Unknown live device orientation')
        if self._foreground() != before:
            raise SceneChanged('Foreground changed during scene observation')
        return Scene(self.session, before[0], before[1], orientation)

    def guard(self, record=lambda event: None):
        return GuardedWDA(self.send, self.live_scene, record, clock=self.clock)

    def observe_ui(self):
        started = self.clock()
        scene = self.live_scene()
        xml = self.read('/source')
        if not isinstance(xml, str):
            raise ProtocolError('UI source must be XML text')
        try:
            ET.fromstring(xml)
            png = base64.b64decode(self.read('/screenshot'), validate=True)
        except (ValueError, TypeError, ET.ParseError) as error:
            raise ProtocolError('Invalid UI observation') from error
        if not png.startswith(b'\x89PNG\r\n\x1a\n'):
            raise ProtocolError('UI screenshot is not PNG')
        if self.live_scene() != scene:
            raise OrientationChanged('Orientation changed during UI observation')
        return UIObservation(scene, started, self.clock(), xml, png)

    def observe_ui_after_rotation(self, before_scene, target_orientation):
        """Read a stable, explicitly expected post-action orientation.

        No action or retry is performed here. Foreground bundle/PID, session and
        automatic targeting remain mandatory. A caller can bound read-only waits
        for OrientationChanged; other scene/protocol failures must still stop it.
        """
        if (not isinstance(before_scene, Scene)
                or (before_scene.session, before_scene.bundle, before_scene.pid)
                != (self.session, self.expected_bundle, self.expected_pid)
                or target_orientation not in ('PORTRAIT', 'LANDSCAPE')
                or before_scene.orientation not in ('PORTRAIT', 'LANDSCAPE')
                or before_scene.orientation == target_orientation):
            raise ValueError('A bound prior scene and different target orientation are required')
        if self.live_scene().orientation != target_orientation:
            raise OrientationChanged('Expected post-action orientation is not current')
        observation = self.observe_ui()
        if observation.scene.orientation != target_orientation:
            raise OrientationChanged('Expected orientation changed before UI capture')
        return observation

    def observe_native_pip(self, record_private):
        """Read only the current PiP container/four controls, never SpringBoard source.

        Each successful selection is unique. Raw request/reply records and the
        final PNG stay private. No retry of element properties, no clicks/reveal.
        Missing or excluded attributes are never inferred to be visible.
        """
        if self.expected_bundle != 'com.apple.springboard' or not callable(record_private):
            raise ValueError('Native PiP scene and private recorder required')
        started = self.clock()
        scene = self.live_scene()
        def checked_scene():
            current = self.live_scene()
            if current != scene:
                raise SceneChanged('Scene changed during native control observation')
            return current
        def send(route, data=None):
            record_private({'phase': 'request', 'route': route, 'data': data})
            reply = self.send(route, data)
            record_private({'phase': 'reply', 'route': route, 'status': reply.status,
                            'body': reply.body.decode('utf-8', errors='replace')})
            return reply
        guard = GuardedWDA(send, checked_scene)
        def target(name, container=False):
            predicate = '' if container else 'type == "XCUIElementTypeButton" AND '
            rows = guard.query_elements({'using': 'predicate string',
                'value': predicate + 'name == ' + json.dumps(name, ensure_ascii=False)})
            if not rows and not container:
                return None
            if len(rows) != 1:
                raise ProtocolError('Native PiP target missing or ambiguous')
            key = rows[0].get('ELEMENT') or rows[0].get('element-6066-11e4-a52e-4f735466cecf')
            if not isinstance(key, str) or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._:-]*', key) or '..' in key:
                raise ProtocolError('Native PiP target identity invalid')
            values = {attribute: decode_reply(send('/element/' + key + '/' + attribute))
                      for attribute in ('displayed', 'enabled', 'rect')}
            rect = values['rect']
            if (type(values['displayed']) is not bool or type(values['enabled']) is not bool
                    or not isinstance(rect, dict) or any(type(rect.get(k)) not in (int, float)
                    or not math.isfinite(rect[k]) for k in ('x', 'y', 'width', 'height'))
                    or min(rect['x'], rect['y']) < 0 or min(rect['width'], rect['height']) <= 0):
                raise ProtocolError('Native PiP properties unavailable')
            return {'name': name, **values}
        container = target('PIP-SBInteractionPassThroughView', True)
        if container['displayed'] is not True:
            raise ProtocolError('Native PiP container is not displayed')
        rect = container['rect']
        controls = []
        for name in ('播放', '暂停', '关闭画中画', '恢复全屏幕'):
            control = target(name)
            if control is not None:
                button = control['rect']
                if not (rect['x'] <= button['x'] + button['width'] / 2 <= rect['x'] + rect['width']
                        and rect['y'] <= button['y'] + button['height'] / 2 <= rect['y'] + rect['height']):
                    raise ProtocolError('Native control is outside the current PiP container')
                controls.append(control)
        try:
            png = base64.b64decode(decode_reply(send('/screenshot')), validate=True)
        except (ValueError, TypeError) as error:
            raise ProtocolError('Native PiP screenshot invalid') from error
        if not png.startswith(b'\x89PNG\r\n\x1a\n'):
            raise ProtocolError('Native PiP screenshot is not PNG')
        checked_scene()
        observation = NativePiPObservation(scene, started, self.clock(), png, rect, tuple(controls))
        record_private({'phase': 'summary', **observation.private_summary()})
        return observation

    def ui_transition_verifier(self, before, *, appeared, disappeared, save_private,
                               native_private_recorder=None):
        """Build a fresh read-only verifier for a visible native control change.

        A private saver is required. This intentionally cannot certify playback
        pause or a restored movie; those need separate same-plan/time/image evidence.
        """
        appeared, disappeared = tuple(appeared), tuple(disappeared)
        if (not isinstance(before, (UIObservation, NativePiPObservation)) or not appeared and not disappeared
                or set(appeared) & set(disappeared) or not callable(save_private)):
            raise ValueError('A prior observation, explicit UI transition and private saver are required')
        if isinstance(before, NativePiPObservation) and not callable(native_private_recorder):
            raise ValueError('Targeted native observation requires a private read recorder')
        if any(not isinstance(n, str) or not n for n in appeared + disappeared):
            raise ValueError('UI transition names must be nonempty text')
        if len(set(appeared)) != len(appeared) or len(set(disappeared)) != len(disappeared):
            raise ValueError('UI transition names must be unique')
        if (any(before.button_count(n) != 0 for n in appeared)
                or any(before.button_count(n) != 1 for n in disappeared)):
            raise ValueError('Prior UI does not match the requested transition')

        used = False
        def verify():
            nonlocal used
            if used:
                raise ProtocolError('UI transition verifier is single-use')
            used = True
            after = (self.observe_native_pip(native_private_recorder)
                     if isinstance(before, NativePiPObservation) else self.observe_ui())
            save_private(after)
            return (after.started > before.finished and after.scene == before.scene
                    and hashlib.sha256(after.png).digest() != hashlib.sha256(before.png).digest()
                    and all(after.button_count(n) == 1 for n in appeared)
                    and all(after.button_count(n) == 0 for n in disappeared))
        return verify
